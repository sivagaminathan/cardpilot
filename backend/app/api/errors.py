"""RFC 9457-compliant Problem Details error handling."""

from typing import Any

from fastapi import Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from starlette.exceptions import HTTPException as StarletteHTTPException


class ProblemDetails(BaseModel):
    """RFC 9457 Problem Details for HTTP APIs."""

    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server.",
    )
    detail: str | None = Field(
        default=None,
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem.",
    )
    errors: list[dict[str, Any]] | None = Field(
        default=None,
        description="Optional list of specific field validation errors.",
    )


async def http_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Handle standard HTTP exceptions with problem details."""
    status_code = exc.status_code if isinstance(exc, StarletteHTTPException) else 500
    detail = exc.detail if isinstance(exc, StarletteHTTPException) else str(exc)
    problem = ProblemDetails(
        type=f"https://cardpilot.demo/errors/http-{status_code}",
        title=detail if isinstance(detail, str) else "HTTP Error",
        status=status_code,
        detail=str(detail),
        instance=str(request.url.path),
    )
    return JSONResponse(
        status_code=status_code,
        content=problem.model_dump(exclude_none=True),
        headers={"Content-Type": "application/problem+json"},
    )


async def validation_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Handle request validation errors with problem details."""
    if not isinstance(exc, RequestValidationError):
        return await http_exception_handler(request, exc)

    formatted_errors = [
        {
            "loc": [str(loc) for loc in err.get("loc", [])],
            "msg": err.get("msg", ""),
            "type": err.get("type", ""),
        }
        for err in exc.errors()
    ]
    problem = ProblemDetails(
        type="https://cardpilot.demo/errors/validation-error",
        title="Unprocessable Entity",
        status=422,
        detail="Request validation failed. Check the errors field for details.",
        instance=str(request.url.path),
        errors=formatted_errors,
    )
    return JSONResponse(
        status_code=422,
        content=problem.model_dump(exclude_none=True),
        headers={"Content-Type": "application/problem+json"},
    )
